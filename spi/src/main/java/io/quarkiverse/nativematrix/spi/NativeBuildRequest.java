package io.quarkiverse.nativematrix.spi;

import java.nio.file.Path;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;
import java.util.Optional;

/**
 * Everything a {@link NativeBuildRunner} needs to build one target of the matrix.
 * <p>
 * Instances are immutable; use {@link #builder()} to create one (mostly useful in tests of custom runners).
 */
public final class NativeBuildRequest {

    /**
     * Directory, relative to the native sources directory, in which runners should let {@code native-image} write its
     * output when they use {@link #nativeImageArgs()}.
     */
    public static final String DEFAULT_OUTPUT_DIR = "output";

    private final String buildId;
    private final String targetName;
    private final Platform platform;
    private final Path nativeSourcesDirectory;
    private final String outputName;
    private final List<String> nativeImageArgs;
    private final Optional<String> graalVmVersion;
    private final Optional<String> builderImage;
    private final RunnerOptions options;
    private final Path outputDirectory;
    private final Duration timeout;

    private NativeBuildRequest(Builder b) {
        this.buildId = Objects.requireNonNull(b.buildId, "buildId");
        this.targetName = Objects.requireNonNull(b.targetName, "targetName");
        this.platform = Objects.requireNonNull(b.platform, "platform");
        this.nativeSourcesDirectory = Objects.requireNonNull(b.nativeSourcesDirectory, "nativeSourcesDirectory");
        this.outputName = Objects.requireNonNull(b.outputName, "outputName");
        this.nativeImageArgs = List.copyOf(b.nativeImageArgs);
        this.graalVmVersion = Optional.ofNullable(b.graalVmVersion);
        this.builderImage = Optional.ofNullable(b.builderImage);
        this.options = b.options == null ? RunnerOptions.empty() : b.options;
        this.outputDirectory = Objects.requireNonNull(b.outputDirectory, "outputDirectory");
        this.timeout = b.timeout == null ? Duration.ofHours(2) : b.timeout;
    }

    public static Builder builder() {
        return new Builder();
    }

    public Builder toBuilder() {
        Builder b = new Builder();
        b.buildId = buildId;
        b.targetName = targetName;
        b.platform = platform;
        b.nativeSourcesDirectory = nativeSourcesDirectory;
        b.outputName = outputName;
        b.nativeImageArgs = new ArrayList<>(nativeImageArgs);
        b.graalVmVersion = graalVmVersion.orElse(null);
        b.builderImage = builderImage.orElse(null);
        b.options = options;
        b.outputDirectory = outputDirectory;
        b.timeout = timeout;
        return b;
    }

    /**
     * @return an identifier shared by all targets of one matrix build, safe to use in file, container and branch names
     *         (lower case letters, digits and dashes)
     */
    public String buildId() {
        return buildId;
    }

    /**
     * @return the name of the target in the configuration, e.g. {@code macos-arm64} or {@code my-pi}
     */
    public String targetName() {
        return targetName;
    }

    public Platform platform() {
        return platform;
    }

    /**
     * @return the local {@code target/native-sources} directory: the runner jar, {@code lib/} and the files generated by
     *         Quarkus. Runners must treat it as read-only, it is shared by all targets.
     */
    public Path nativeSourcesDirectory() {
        return nativeSourcesDirectory;
    }

    /**
     * @return the executable base name chosen by Quarkus, e.g. {@code my-app-1.0.0-runner}, without OS suffix
     */
    public String outputName() {
        return outputName;
    }

    /**
     * @return the executable file name on the target platform, e.g. {@code my-app-1.0.0-runner.exe} on Windows
     */
    public String executableName() {
        return platform.executableName(outputName);
    }

    /**
     * The {@code native-image} arguments, already adjusted for the target platform, writing the executable to
     * {@code output/<outputName>} relative to the native sources directory. They must be passed to {@code native-image}
     * from within (a copy of) the native sources directory. Prefer writing them to an argument file with
     * {@link io.quarkiverse.nativematrix.spi.support.ArgFile} rather than passing them on a command line: they may
     * contain characters that shells interpret.
     */
    public List<String> nativeImageArgs() {
        return nativeImageArgs(DEFAULT_OUTPUT_DIR + "/" + outputName);
    }

    /**
     * Same as {@link #nativeImageArgs()} but with a custom output path ({@code -o} value). Use forward slashes; GraalVM
     * accepts them on every OS.
     */
    public List<String> nativeImageArgs(String outputPath) {
        List<String> args = new ArrayList<>(nativeImageArgs.size() + 2);
        boolean replaced = false;
        for (int i = 0; i < nativeImageArgs.size(); i++) {
            String arg = nativeImageArgs.get(i);
            if ("-o".equals(arg) && i + 1 < nativeImageArgs.size()) {
                args.add("-o");
                args.add(outputPath);
                i++;
                replaced = true;
            } else {
                args.add(arg);
            }
        }
        if (!replaced) {
            int jar = args.indexOf("-jar");
            int at = jar < 0 ? args.size() : jar;
            args.add(at, outputPath);
            args.add(at, "-o");
        }
        return args;
    }

    /**
     * @return the GraalVM version the native sources were generated for (from {@code native-sources/graalvm.version}).
     *         Running a very different {@code native-image} version may fail on unknown options.
     */
    public Optional<String> graalVmVersion() {
        return graalVmVersion;
    }

    /**
     * @return the builder image configured in Quarkus ({@code quarkus.native.builder-image}), if known. Container based
     *         runners use it as their default image.
     */
    public Optional<String> builderImage() {
        return builderImage;
    }

    /**
     * @return runner specific options, see {@link NativeBuildRunner}
     */
    public RunnerOptions options() {
        return options;
    }

    /**
     * @return the local, empty, directory the runner must copy the executable and its companion files (shared
     *         libraries, debug symbols...) into
     */
    public Path outputDirectory() {
        return outputDirectory;
    }

    /**
     * @return the maximum time the build may take; the orchestrator interrupts the runner after that
     */
    public Duration timeout() {
        return timeout;
    }

    @Override
    public String toString() {
        return "NativeBuildRequest[" + targetName + " (" + platform + ")]";
    }

    public static final class Builder {
        private String buildId;
        private String targetName;
        private Platform platform;
        private Path nativeSourcesDirectory;
        private String outputName;
        private List<String> nativeImageArgs = new ArrayList<>();
        private String graalVmVersion;
        private String builderImage;
        private RunnerOptions options;
        private Path outputDirectory;
        private Duration timeout;

        private Builder() {
        }

        public Builder buildId(String buildId) {
            this.buildId = buildId;
            return this;
        }

        public Builder targetName(String targetName) {
            this.targetName = targetName;
            return this;
        }

        public Builder platform(Platform platform) {
            this.platform = platform;
            return this;
        }

        public Builder nativeSourcesDirectory(Path nativeSourcesDirectory) {
            this.nativeSourcesDirectory = nativeSourcesDirectory;
            return this;
        }

        public Builder outputName(String outputName) {
            this.outputName = outputName;
            return this;
        }

        public Builder nativeImageArgs(List<String> nativeImageArgs) {
            this.nativeImageArgs = new ArrayList<>(nativeImageArgs);
            return this;
        }

        public Builder graalVmVersion(String graalVmVersion) {
            this.graalVmVersion = graalVmVersion;
            return this;
        }

        public Builder builderImage(String builderImage) {
            this.builderImage = builderImage;
            return this;
        }

        public Builder options(RunnerOptions options) {
            this.options = options;
            return this;
        }

        public Builder outputDirectory(Path outputDirectory) {
            this.outputDirectory = outputDirectory;
            return this;
        }

        public Builder timeout(Duration timeout) {
            this.timeout = timeout;
            return this;
        }

        public NativeBuildRequest build() {
            return new NativeBuildRequest(this);
        }
    }
}
